TITLEFONT=Font(name=FONT, bold=True, color=PINKD, size=15)
SUBFONT=Font(name=FONT, color=GREY, size=9, italic=True)
WRAP=Alignment(wrap_text=True, vertical="center")
WRAPC=Alignment(wrap_text=True, vertical="center", horizontal="center")

LEVEL={"พร้อม":(OKBG,OKFG), "บางส่วน":(WARNBG,WARNFG), "ยังไม่มี":(BADBG,BADFG),
       "คงไว้":(OKBG,OKFG), "รอตัดสินใจ":(WARNBG,WARNFG), "ตัดออก":(BADBG,BADFG)}


def sheet(wb, name, title, sub, headers, rows, widths, first=False, status_col=None):
    ws = wb.active if first else wb.create_sheet()
    ws.title = name
    ws["A1"] = title; ws["A1"].font = TITLEFONT
    ws["A2"] = sub;   ws["A2"].font = SUBFONT
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    hr = 4
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=hr, column=i, value=h)
        c.fill = HFILL; c.font = HFONT; c.border = BORDER; c.alignment = WRAPC
    r = hr + 1
    for row in rows:
        for i, val in enumerate(row, 1):
            c = ws.cell(row=r, column=i, value=val)
            c.font = CFONT; c.border = BORDER
            c.alignment = WRAPC if (status_col and i == status_col) else WRAP
            if (r - hr) % 2 == 0:
                c.fill = ZEBRA
            if status_col and i == status_col and val in LEVEL:
                bg, fg = LEVEL[val]
                c.fill = PatternFill("solid", fgColor=bg)
                c.font = Font(name=FONT, bold=True, color=fg, size=10)
        ws.row_dimensions[r].height = 32
        r += 1
    ws.freeze_panes = f"A{hr+1}"
    return ws


