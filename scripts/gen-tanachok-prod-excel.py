FONT="Tahoma"

thin=Side(style="thin", color="E3DBE0")
BORDER=Border(left=thin,right=thin,top=thin,bottom=thin)
HFILL=PatternFill("solid", fgColor=PINK)
ZEBRA=PatternFill("solid", fgColor=LIGHT)
